-- =====================================================================
-- DDL - Banco "tcc" (PostgreSQL)
-- Rodar inteiro: ele apaga as tabelas antigas e cria tudo de novo.
--   psql -U postgres -d tcc -f DDL.SQL
--   psql -U postgres -d tcc -f DML.SQL
--
-- Convenção de nomes:
--   - tabelas: snake_case, no plural (alunos, turmas, ...)
--   - chave primária: id
--   - chave estrangeira: id_<entidade> (id_aluno, id_turma, id_ocorrencia)
--   - colunas: snake_case, sem "de/do/da", com o mesmo nome do campo/@Column do Model Java
--   - valores fixos em MAIÚSCULO, iguais ao Java:
--       turno: MANHA, TARDE, NOITE, INTEGRAL (enum Turno)
--       tipo_ocorrencia: ATRASO, SAIDA_ANTECIPADA
-- =====================================================================

DROP TABLE IF EXISTS alertas CASCADE;
DROP TABLE IF EXISTS anexos CASCADE;
DROP TABLE IF EXISTS ocorrencias CASCADE;
DROP TABLE IF EXISTS alunos CASCADE;
DROP TABLE IF EXISTS turmas CASCADE;
DROP TABLE IF EXISTS secretarias CASCADE;


-- Cadastro de Secretarias (Model Usuario)
CREATE TABLE secretarias (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(255) NOT NULL,
  masp varchar(255) NOT NULL UNIQUE,
  cpf varchar(255),
  email_institucional varchar(255) NOT NULL UNIQUE,
  turno varchar(20) NOT NULL CHECK (turno IN ('MANHA', 'TARDE', 'NOITE', 'INTEGRAL')),
  senha varchar(255) NOT NULL
);


-- Cadastro de Turmas (Model Turma)
CREATE TABLE turmas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(255) NOT NULL,
  serie varchar(255) NOT NULL,
  turno varchar(20) NOT NULL CHECK (turno IN ('MANHA', 'TARDE', 'NOITE', 'INTEGRAL')),
  ano_letivo int
);


-- Cadastro de Alunos (Model Aluno)
-- "turma" guarda o nome da turma (ex: '3º Ano 1'), igual ao Model Aluno
CREATE TABLE alunos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar(255) NOT NULL,
  cpf varchar(255) NOT NULL UNIQUE,
  data_nascimento date,
  turma varchar(255),
  turno varchar(20) NOT NULL CHECK (turno IN ('MANHA', 'TARDE', 'NOITE', 'INTEGRAL')),
  genero varchar(255),
  raca varchar(255),
  nacionalidade varchar(255),
  nome_responsavel varchar(255) NOT NULL,
  cpf_responsavel varchar(255),
  telefone_responsavel varchar(255),
  email_responsavel varchar(255),
  endereco varchar(255)
);


-- Atrasos e Saídas Antecipadas (Model Acao)
CREATE TABLE ocorrencias (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_aluno bigint NOT NULL REFERENCES alunos (id) ON DELETE CASCADE,
  id_turma bigint REFERENCES turmas (id) ON DELETE SET NULL,
  data_ocorrencia date NOT NULL,
  hora_ocorrencia time NOT NULL,
  tipo_ocorrencia varchar(20) NOT NULL CHECK (tipo_ocorrencia IN ('ATRASO', 'SAIDA_ANTECIPADA')),
  justificativa varchar(255),
  observacao varchar(255)
);


-- Anexo de atestados médicos e outros documentos (parte "documento" do Model Acao)
-- Cada ocorrência tem no máximo 1 anexo. A imagem é o arquivo em bytes (upload).
CREATE TABLE anexos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_ocorrencia bigint NOT NULL UNIQUE REFERENCES ocorrencias (id) ON DELETE CASCADE,
  tipo_documento varchar(255),
  imagem_documento bytea,
  descricao_documento varchar(255)
);


-- Alertas de limite de atrasos (Model Alerta)
CREATE TABLE alertas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_aluno bigint NOT NULL REFERENCES alunos (id) ON DELETE CASCADE,
  nome_aluno varchar(255),
  turma varchar(255),
  mensagem varchar(500),
  limite_atingido boolean NOT NULL DEFAULT false,
  atrasos_semanal int NOT NULL DEFAULT 0,
  saidas_semanal int NOT NULL DEFAULT 0,
  atrasos_mensal int NOT NULL DEFAULT 0,
  saidas_mensal int NOT NULL DEFAULT 0,
  data_alerta timestamp NOT NULL DEFAULT now(),
  lido boolean NOT NULL DEFAULT false
);
